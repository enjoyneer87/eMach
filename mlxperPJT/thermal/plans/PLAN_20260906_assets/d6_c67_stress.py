def _clim_for(arr, lo_pct, hi_pct):
    lo = _percentile(arr, lo_pct)
    hi = _percentile(arr, hi_pct)
    if _is_nan(lo) or _is_nan(hi) or hi <= lo:
        lo, hi = _nanmin(arr), _nanmax(arr)
    if _is_nan(lo) or _is_nan(hi) or hi <= lo:
        return None
    return [float(lo), float(hi)]


def _contour_pyvista(fields, key, bar_title, clim, cmap, log):
    """pyvista off_screen 렌더 -> RGB 배열.  실패하면 None (matplotlib 로 폴백)."""
    try:
        import pyvista as pv
    except Exception as exc:
        log("  pyvista unavailable (%s) -> matplotlib fallback" % exc)
        return None
    # pv.start_xvfb() 는 Linux 전용이다.  moa 는 Windows 이므로 절대 부르지 않는다.
    try:
        pv.OFF_SCREEN = True
        grid = fields.get("grid")
        arr = _np.asarray(fields[key], dtype=float)
        obj = None
        if grid is not None and hasattr(grid, "n_points"):
            if int(grid.n_points) == arr.size:
                obj = grid
            else:
                # 그리드 점 순서 != 필드 순서.  절점번호 배열이 있으면 재정렬해서
                # 살리고, 없으면 점구름으로 내려간다 (그림만 거칠어질 뿐 값은 같다).
                try:
                    gnum = None
                    for k in ("ansys_node_num", "node_num", "NodeIds"):
                        if k in grid.point_data:
                            gnum = _np.asarray(grid.point_data[k])
                            break
                    if gnum is not None and gnum.size == int(grid.n_points):
                        arr = _align_to(gnum, fields["nnum"], arr, 1, log=log,
                                        label="grid remap")
                        obj = grid
                        log("  pyvista: remapped the field onto the grid by node id")
                except Exception as exc:
                    log("  pyvista: grid remap failed (%s)" % str(exc)[:120])
            if obj is None:
                log("  pyvista: grid n_points (%d) != field length (%d) -> point "
                    "cloud" % (int(grid.n_points), arr.size))
        point_cloud = obj is None
        if point_cloud:
            obj = pv.PolyData(_np.asarray(fields["xyz_mm"], dtype=float))
        obj = obj.copy()
        obj[bar_title] = _np.asarray(arr, dtype=float)
        pl = pv.Plotter(off_screen=True, window_size=(900, 720))
        pl.set_background("white")
        kw = dict(scalars=bar_title, cmap=cmap, show_edges=False,
                  nan_opacity=0.0,
                  scalar_bar_args=dict(title=bar_title, vertical=True,
                                       title_font_size=14, label_font_size=11,
                                       color="black"))
        if clim:
            kw["clim"] = clim
        if point_cloud:
            kw["render_points_as_spheres"] = False
            kw["point_size"] = 3.0
        try:
            pl.add_mesh(obj, **kw)
        except TypeError as exc:
            # pyvista 버전 차이로 exotic kwarg 가 없을 수 있다 -> 최소 인자로 재시도.
            log("  pyvista: add_mesh(**kw) rejected (%s) -> minimal kwargs"
                % str(exc)[:120])
            kw2 = dict(scalars=bar_title, cmap=cmap, show_edges=False)
            if clim:
                kw2["clim"] = clim
            pl.add_mesh(obj, **kw2)
        pl.view_xy()
        pl.camera.zoom(1.25)
        img = pl.screenshot(return_img=True)
        pl.close()
        log("  pyvista: rendered %s (%dx%d)" % (bar_title, img.shape[1], img.shape[0]))
        return img
    except Exception as exc:
        log("  pyvista render failed (%s: %s) -> matplotlib fallback"
            % (type(exc).__name__, str(exc)[:160]))
        return None


def _contour_matplotlib(ts, fields, key, title, bar_title, path, clim, cmap,
                        args, log):
    """xy 투영 산점 컨투어.  값이 큰 절점이 위에 오도록 정렬해서 그린다."""
    import matplotlib.pyplot as plt

    x = _np.asarray([p[0] for p in fields["xyz_mm"]], dtype=float) \
        if not isinstance(fields["xyz_mm"], _np.ndarray) \
        else fields["xyz_mm"][:, 0]
    y = _np.asarray([p[1] for p in fields["xyz_mm"]], dtype=float) \
        if not isinstance(fields["xyz_mm"], _np.ndarray) \
        else fields["xyz_mm"][:, 1]
    v = _np.asarray(fields[key], dtype=float)

    ok = _np.isfinite(v)
    x, y, v = x[ok], y[ok], v[ok]
    n_max = int(args.max_plot_nodes)
    n_plotted = int(v.size)
    if v.size > n_max:
        step = int(math.ceil(v.size / float(n_max)))
        x, y, v = x[::step], y[::step], v[::step]
        n_plotted = int(v.size)
        log("  matplotlib: subsampled every %d-th node -> %d plotted"
            % (step, n_plotted))
    order = _np.argsort(v)             # 큰 값이 마지막에 그려져 위로 온다
    x, y, v = x[order], y[order], v[order]

    fig, ax = plt.subplots(figsize=ts.FIGSIZE["raster"])
    sc = ax.scatter(x, y, c=v, s=float(args.marker_size), cmap=cmap, linewidths=0,
                    vmin=(clim[0] if clim else None),
                    vmax=(clim[1] if clim else None))
    ax.set_aspect("equal")
    ax.set_xlabel(ts.check_label("x [mm]"))
    ax.set_ylabel(ts.check_label("y [mm]"))
    ax.set_title(ts.check_label(title), fontsize=10, color=ts.INK, pad=6)
    cb = fig.colorbar(sc, ax=ax, fraction=0.046, pad=0.03)
    cb.set_label(ts.check_label(bar_title))
    fig.tight_layout(pad=0.3)
    res = ts.savefig_guarded(fig, path, dpi=float(args.contour_dpi),
                             max_bytes=int(args.png_max_kb) * 1024)
    plt.close(fig)
    res["backend"] = "matplotlib scatter (xy projection, value-sorted)"
    res["n_plotted"] = n_plotted
    return res


def make_contour(ts, fields, key, title, bar_title, path, cmap, args, log):
    clim = _clim_for(fields[key], float(args.clim_lo_pct), float(args.clim_hi_pct))
    log("  %s: clim = %s" % (os.path.basename(path),
                             "auto-none" if clim is None
                             else "[%.4g, %.4g]" % (clim[0], clim[1])))
    img = None
    if not args.no_pyvista:
        img = _contour_pyvista(fields, key, bar_title, clim, cmap, log)
    if img is not None:
        # VTK 는 한글을 못 그린다 -> 제목은 matplotlib 이 붙인다.
        res = ts.png_from_pyvista(img, title, path, dpi=float(args.contour_dpi),
                                  max_bytes=int(args.png_max_kb) * 1024)
        res["backend"] = "pyvista off_screen + matplotlib title composite"
