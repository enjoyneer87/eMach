def pick_reader(requested, avail, log):
    """실제로 시도할 리더 후보를 **순서대로** 돌려준다.

    `--reader` 를 명시하면 그것 하나만.  `auto` 면 dpf -> mapdl_reader 순으로
    후보를 만든다 (import 가 되는 것만).  DPF 의 세부 API(`stress_von_mises` 노출,
    `von_mises_eqv_fc` 시그니처)는 이 레포에서 한 번도 검증된 적이 없으므로
    **첫 후보가 예외를 던지면 다음 후보로 넘어간다** -- 그래서 리스트다.
    `mapdl`(ansys.mapdl.core)은 rst 단독으로는 못 읽으므로 이 목록에 넣지 않는다.
    """
    order = ("dpf", "mapdl_reader")
    if requested == "mapdl":
        raise RuntimeError(
            "--reader mapdl cannot read a lone .rst: MAPDL /POST1 needs the node/"
            "element database (file.db / .cdb / ds.dat), which a Workbench MECH "
            "folder does not save by default.  Drop --rst and pass --mech-dir so the "
            "model is re-solved, or use --reader mapdl_reader / dpf.")
    if requested and requested != "auto":
        if avail.get(requested) is None:
            raise RuntimeError("--reader %s requested but the module is not "
                               "importable (probe said missing)" % requested)
        return [requested]
    cands = [n for n in order if avail.get(n)]
    if not cands:
        raise RuntimeError(
            "no result reader available.  Install one into the moa venv:\n"
            "  <venv>\\Scripts\\python.exe -m pip install ansys-mapdl-reader\n"
            "  (or ansys-dpf-core).  ansys-mapdl-core alone cannot read a lone .rst; "
            "for that route pass --mech-dir with ds.dat / file.db / a .cdb.")
    log("  reader candidates (in order): %s" % ", ".join(cands))
    return cands


