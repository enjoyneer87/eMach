def omega_rad_s(rpm):
    """rpm -> rad/s.   MAPDL `OMEGA,,,wz` 에 그대로 들어가는 값."""
    return float(rpm) * 2.0 * math.pi / 60.0


def omega2_scale(rpm, rpm_ref):
    """(n/n_ref)^2.

    선형탄성 + 순수 원심체적력 f = rho*omega^2*r + 동차 변위 BC 이면 지배방정식이
    omega^2 에 완전히 선형이므로  sigma(n) = sigma(n_ref)*(n/n_ref)^2  는
    **근사가 아니라 정확한 항등식**이다.  깨지는 조건은 4 가지뿐:
      (a) 소성/비선형 재료  (b) frictional 접촉의 개폐 변화
      (c) 압입/열하중 등 속도에 무관한 상수항  (d) NLGEOM/spin softening
    C67 은 슬리브 0 / 밴딩 0 / 축공 0 이라 (c) 는 없고, bonded 이면 (b) 도 없다.
    Neuber/Glinka 소성보정을 **적용한 뒤의** 값에는 절대 쓰면 안 된다.
    """
    return (float(rpm) / float(rpm_ref)) ** 2


