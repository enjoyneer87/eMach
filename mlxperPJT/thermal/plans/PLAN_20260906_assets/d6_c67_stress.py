def _loc(fields, i):
    xyz = fields["xyz_mm"]
    return {"x": float(xyz[i][0]), "y": float(xyz[i][1]), "z": float(xyz[i][2]),
            "r": float(fields["r_mm"][i]), "theta_deg": float(fields["theta_deg"][i])}


def _mask_stats(fields, lo_mm, hi_mm):
    """반경 밴드 [lo, hi] mm 안의 통계."""
    r = fields["r_mm"]
    svm = fields["svm_MPa"]
    ur = fields.get("u_r_mm")
    if _np is not None and isinstance(r, _np.ndarray):
        m = (r >= lo_mm) & (r <= hi_mm)
        n = int(m.sum())
        if n == 0:
            return {"n_nodes": 0, "max_svm_MPa": None, "mean_svm_MPa": None,
                    "max_ur_mm": None, "r_mm_range": [lo_mm, hi_mm]}
        s = svm[m]
        out = {"n_nodes": n, "max_svm_MPa": _nanmax(s), "mean_svm_MPa": _nanmean(s),
               "r_mm_range": [lo_mm, hi_mm]}
        out["max_ur_mm"] = _nanmax(ur[m]) if ur is not None else None
        return out
    sel_s, sel_u, n = [], [], 0
    for i in range(len(r)):
        if lo_mm <= r[i] <= hi_mm:
            n += 1
            sel_s.append(svm[i])
            if ur is not None:
                sel_u.append(ur[i])
    if n == 0:
        return {"n_nodes": 0, "max_svm_MPa": None, "mean_svm_MPa": None,
                "max_ur_mm": None, "r_mm_range": [lo_mm, hi_mm]}
    return {"n_nodes": n, "max_svm_MPa": _nanmax(sel_s),
            "mean_svm_MPa": _nanmean(sel_s),
            "max_ur_mm": (_nanmax(sel_u) if sel_u else None),
            "r_mm_range": [lo_mm, hi_mm]}


def extract_maxima(fields, args, log):
    """최대 von Mises / 최대 반경변위와 그 절점번호·좌표(mm)를 뽑는다."""
    svm = fields["svm_MPa"]
    ur = fields["u_r_mm"]
    umag = fields["u_mag_mm"]
    nnum = fields["nnum"]

    i_s = _nanargmax(svm)
    i_u = _nanargmax(ur)
    i_m = _nanargmax(umag)
    if i_s < 0 or i_u < 0:
        raise RuntimeError("all-NaN stress or displacement field -- wrong result "
                           "set, or the reader returned nothing")

    res = {
        "rpm": float(args.rpm),
        "omega_rad_s": omega_rad_s(args.rpm),
        "max_von_mises_MPa": float(svm[i_s]),
        "max_von_mises_node": int(nnum[i_s]),
        "max_von_mises_loc_mm": _loc(fields, i_s),
        "max_radial_disp_mm": float(ur[i_u]),
        "max_radial_disp_node": int(nnum[i_u]),
        "max_radial_disp_loc_mm": _loc(fields, i_u),
        "min_radial_disp_mm": _nanmin(ur),
        "max_total_disp_mm": float(umag[i_m]),
        "max_total_disp_node": int(nnum[i_m]),
        "mean_von_mises_MPa": _nanmean(svm),
        "delta_r_definition": ("u_r = ux*cos(theta) + uy*sin(theta), "
                               "theta = atan2(y, x), rotation axis = Z "
                               "(signed projection, NOT sqrt(ux^2+uy^2))"),
        "n_nodes": int(len(nnum)),
    }
    rr = args.rotor_r_mm
    res["per_region"] = {
        "bore": _mask_stats(fields, 0.0, args.shaft_r_mm * 1.001),
        "annulus": _mask_stats(fields, args.shaft_r_mm * 0.999, rr * 1.001),
        "rim": _mask_stats(fields, rr * 0.95, rr * 1.001),
    }
    res["_region_method"] = (
        "radial bands on sqrt(x^2+y^2) -- the reader route carries no component or "
        "material identity, so 'rotor lamination' vs 'magnet' cannot be separated "
        "without the MAPDL database.  Bands are [0, r_shaft], [r_shaft, r_rotor], "
        "[0.95*r_rotor, r_rotor].")

    # 공극을 잡아먹는 것은 **외경(rim)** 의 반경변위이지 전역 최대가 아니다.
    # 자유-자유 원환에서는 보어 쪽 u_r 이 더 크기 때문에(u_r(a) > u_r(b)) 전역 최대를
    # 쓰면 공극 소모를 과대평가한다.
    rim_ur = res["per_region"]["rim"].get("max_ur_mm")
    res["max_rim_radial_disp_mm"] = rim_ur
    ur_for_gap = rim_ur if rim_ur is not None else res["max_radial_disp_mm"]
    res["airgap_consumed_pct"] = (100.0 * ur_for_gap / args.airgap_mm
                                  if args.airgap_mm > 0 else None)
    res["airgap_consumed_basis"] = ("max u_r over the rim band "
                                    "[0.95*r_rotor, r_rotor]"
                                    if rim_ur is not None else "global max u_r")
    res["yield_MPa"] = args.yield_MPa
    res["safety_factor"] = (None if args.yield_MPa is None
                            else float(args.yield_MPa) / res["max_von_mises_MPa"])
    res["safety_factor_note"] = (
        "safety_factor = yield_MPa / max_von_mises_MPa.  20PN1150F yield strength is "
        "NOT known -- Motor-CAD's 305 MPa (ActiveXParametersMotorCADv261.txt #5007) is "
        "a program default, not a datasheet value for this steel.  The thesis side "
        "fills this in (PLAN D6 TODO (i)); pass --yield-MPa to compute it here.")

    log("  max von Mises   : %.4f MPa at node %d  (x %.3f, y %.3f, z %.3f mm, "
        "r %.3f mm, theta %.2f deg)"
        % (res["max_von_mises_MPa"], res["max_von_mises_node"],
           res["max_von_mises_loc_mm"]["x"], res["max_von_mises_loc_mm"]["y"],
           res["max_von_mises_loc_mm"]["z"], res["max_von_mises_loc_mm"]["r"],
           res["max_von_mises_loc_mm"]["theta_deg"]))
    pct = res["airgap_consumed_pct"]
    log("  max radial disp : %.6f mm at node %d  (r %.3f mm) -> %.2f %% of the "
        "%.2f mm airgap"
        % (res["max_radial_disp_mm"], res["max_radial_disp_node"],
           res["max_radial_disp_loc_mm"]["r"],
           float("nan") if pct is None else pct, args.airgap_mm))
    return res


