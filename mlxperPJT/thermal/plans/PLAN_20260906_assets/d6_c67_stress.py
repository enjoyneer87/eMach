def rel_to_repo(path, repo):
    """repo 기준 상대경로.  다른 드라이브면 relpath 가 ValueError 를 던지므로
    (Windows 에서 흔하다 -- 레포 E:\\, 출력 C:\\) 절대경로로 폴백한다."""
    try:
        return os.path.relpath(path, repo).replace("\\", "/")
    except ValueError:
        return os.path.abspath(path).replace("\\", "/")


def sha256_of(path, max_bytes=None):
    h = hashlib.sha256()
    n = 0
    with open(path, "rb") as f:
        while True:
            b = f.read(1 << 20)
            if not b:
                break
            h.update(b)
            n += len(b)
            if max_bytes and n >= max_bytes:
                break
    return h.hexdigest()


def check_gitignore(paths, repo, log):
    """.gitignore:39 `*.png` 가 thesis_out PNG 를 조용히 삼킨다 -- 커밋 전에 경고.

    고치는 방법은 루트 .gitignore 맨 끝에 negation 한 줄:
        !mlxperPJT/thermal/thesis_out/*.png
    이 파일은 plans/ 밖이므로 **moa 가** 적용한다.  임시 회피는 `git add -f`.
    """
    out = {"checked": [], "ignored": [], "skipped": [], "git_available": False,
           "fix_patch": "!mlxperPJT/thermal/thesis_out/*.png",
           "fix_note": ("append the line above to the ROOT .gitignore (it lives "
                        "outside plans/, so moa applies it), or commit with "
                        "`git add -f <png>`; verify with `git ls-files`")}
    for p in paths:
        if not p:
            continue
        out["checked"].append(p)
        try:
            # ** verdict WITHOUT -v **. With -v, git check-ignore exits 0 whenever ANY
            # pattern matched -- including a NEGATION (!...). Once .gitignore carries
            # `!mlxperPJT/thermal/thesis_out/*.png`, the -v form reports a perfectly
            # committable PNG as ignored. Measured on moa 2026-09-07: -q -> exit 1
            # (committable), -v -> exit 0 (ignored), same file. -v is used afterwards
            # only to fetch the rule text.
            r = subprocess.run(["git", "-C", repo, "check-ignore", p],
                               stdout=subprocess.PIPE, stderr=subprocess.PIPE)
            out["git_available"] = True
            # git check-ignore exit codes: 0 = ignored, 1 = NOT ignored,
            # anything else (128) = the question was never asked -- the path is
            # outside the repo, or this is not a git work tree.  Reporting 128 as
            # "not ignored" would be a false all-clear, so it is a SKIP, not a pass.
            if r.returncode == 0:
                _v = subprocess.run(["git", "-C", repo, "check-ignore", "-v", p],
                                    stdout=subprocess.PIPE, stderr=subprocess.PIPE)
                rule = _v.stdout.decode("utf-8", "replace").strip()
                out["ignored"].append({"path": p, "rule": rule})
                log("  GITIGNORE WARN: %s is ignored by %s" % (os.path.basename(p),
                                                               rule))
            elif r.returncode != 1:
                why = r.stderr.decode("utf-8", "replace").strip().splitlines()
                why = why[0] if why else "git exit %d" % r.returncode
                out["skipped"].append({"path": p, "reason": why})
        except Exception as exc:
            log("  git check-ignore unavailable (%s)" % exc)
            break
    if out["ignored"]:
        log("  => %d output file(s) will NOT be committed as-is.  Fix: append"
            % len(out["ignored"]))
        log("     %s" % out["fix_patch"])
        log("     to the ROOT .gitignore, or use `git add -f`.")
    if out["skipped"]:
        log("  git check-ignore SKIPPED for %d of %d path(s) -- NOT an all-clear: %s"
            % (len(out["skipped"]), len(out["checked"]),
               out["skipped"][0]["reason"]))
        log("     (these outputs are outside the repo, so this run tells you nothing")
        log("      about whether thesis_out PNGs would be committed. Re-check with")
        log("      --out inside the repo before the promotion commit.)")
    if out["git_available"] and not out["ignored"] and not out["skipped"]:
        log("  git check-ignore: no output file is ignored")
    return out


