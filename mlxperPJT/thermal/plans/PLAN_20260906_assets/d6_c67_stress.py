def annulus_plane_stress(rpm, a_m, b_m, nu, rho, E_Pa):
    """자유-자유 회전 원환(내경 a, 외경 b, 평면응력)의 닫힌해.

        sigma_r(r)     = (3+nu)/8 * rho*w^2 * (a^2 + b^2 - a^2 b^2/r^2 - r^2)
        sigma_theta(r) = (3+nu)/8 * rho*w^2 * (a^2 + b^2 + a^2 b^2/r^2
                                               - (1+3nu)/(3+nu) * r^2)
        u_r(r)         = r*(sigma_theta - nu*sigma_r)/E

    반환 dict 의 응력 단위는 MPa, 변위 단위는 um / mm.
    """
    w = omega_rad_s(rpm)
    c = (3.0 + nu) / 8.0 * rho * w * w
    k = (1.0 + 3.0 * nu) / (3.0 + nu)
    a2, b2 = a_m * a_m, b_m * b_m

    def s_r(r):
        return c * (a2 + b2 - a2 * b2 / (r * r) - r * r)

    def s_t(r):
        return c * (a2 + b2 + a2 * b2 / (r * r) - k * r * r)

    def u_r(r):
        return r * (s_t(r) - nu * s_r(r)) / E_Pa

    return {
        "rpm": float(rpm),
        "omega_rad_s": w,
        "a_m": float(a_m), "b_m": float(b_m),
        "nu": float(nu), "rho_kg_m3": float(rho), "E_Pa": float(E_Pa),
        "sigma_theta_inner_MPa": s_t(a_m) / 1e6,
        "sigma_theta_outer_MPa": s_t(b_m) / 1e6,
        "sigma_r_inner_MPa": s_r(a_m) / 1e6,
        "sigma_r_outer_MPa": s_r(b_m) / 1e6,
        "u_r_outer_um": u_r(b_m) * 1e6,
        "u_r_outer_mm": u_r(b_m) * 1e3,
        "_field_fn": {"s_r": s_r, "s_t": s_t, "u_r": u_r},
        "_note": ("free-free rotating annulus, plane stress, homogeneous isotropic; "
                  "no bridges/posts/magnets -> FE max von Mises is expected to be "
                  "2-4x the bore hoop stress"),
    }


def verify_analytic_formula(log):
    """공식 자체가 맞는지(오타가 없는지) 18 krpm 고정 기준값과 대조한다.

    Ansys 가 없어도 무조건 실행되는 self-check.  실패하면 즉시 죽는다 --
    이 공식이 틀리면 아래의 모든 sanity 판정이 거짓말이 된다.
    """
    ref = ANALYTIC_REF_18K
    got = annulus_plane_stress(ref["rpm"], 0.035, 0.075, 0.3, 7650.0, 192.5e9)
    checks = []
    for key in ("omega_rad_s", "sigma_theta_inner_MPa",
                "sigma_theta_outer_MPa", "u_r_outer_um"):
        want, have = float(ref[key]), float(got[key])
        rel = abs(have - want) / max(abs(want), 1e-30)
        ok = rel <= ANALYTIC_REF_TOL_REL
        checks.append({"key": key, "expected": want, "got": have,
                       "rel_err": rel, "ok": ok})
        log("    %-24s expected %14.6f   got %14.6f   rel %.2e   %s"
            % (key, want, have, rel, "OK" if ok else "FAIL"))
    bad = [c for c in checks if not c["ok"]]
    if bad:
        raise AssertionError("analytic annulus formula self-check FAILED: %s"
                             % [c["key"] for c in bad])
    return checks


def sanity_gate(max_svm_MPa, max_ur_mm, rpm, ana, log):
    """단위(Pa vs MPa, m vs mm) 오독과 잘못된 set 읽기를 즉시 잡는 게이트.

    * von Mises: 보어 후프응력의 2~4 배가 정상 (브리지/포스트 응력집중).
    * 반경변위 : 18 krpm 기준 20~50 um, 다른 속도에서는 (n/18000)^2 로 스케일.
    PASS / WARN 을 찍고 dict 를 돌려준다.  **WARN 이어도 죽이지 않는다** --
    C67 이 정말로 그 범위 밖일 수도 있고, 판단은 사람이 한다.
    """
    hoop = float(ana["sigma_theta_inner_MPa"])
    svm_lo, svm_hi = SVM_BAND_X_HOOP[0] * hoop, SVM_BAND_X_HOOP[1] * hoop
    sc = omega2_scale(rpm, 18000.0)
    ur_lo = UR_BAND_UM_18K[0] * sc / 1000.0        # um -> mm
    ur_hi = UR_BAND_UM_18K[1] * sc / 1000.0

    warns = []
    svm_ok = (not _is_nan(max_svm_MPa)) and (svm_lo <= max_svm_MPa <= svm_hi)
    ur_ok = (not _is_nan(max_ur_mm)) and (ur_lo <= max_ur_mm <= ur_hi)
    if not svm_ok:
        warns.append("max von Mises %.4g MPa outside [%.4g, %.4g] MPa "
                     "(= %.1f-%.1f x bore hoop %.4g MPa) -- check Pa vs MPa, "
                     "the result set, or accept it as a real design finding"
                     % (max_svm_MPa, svm_lo, svm_hi, SVM_BAND_X_HOOP[0],
                        SVM_BAND_X_HOOP[1], hoop))
    if not ur_ok:
        warns.append("max radial displacement %.4g mm outside [%.4g, %.4g] mm "
                     "-- check m vs mm" % (max_ur_mm, ur_lo, ur_hi))

    log("  analytic annulus @%.0f rpm : hoop(bore) %.2f MPa, hoop(rim) %.2f MPa, "
        "u_r(rim) %.2f um" % (rpm, hoop, ana["sigma_theta_outer_MPa"],
                              ana["u_r_outer_um"]))
    log("  expected FE band          : von Mises [%.1f, %.1f] MPa, "
        "delta_r [%.4f, %.4f] mm" % (svm_lo, svm_hi, ur_lo, ur_hi))
    log("  measured                  : von Mises %.4g MPa, delta_r %.5g mm"
        % (max_svm_MPa, max_ur_mm))
    log("  SANITY GATE: %s" % ("PASS" if (svm_ok and ur_ok) else "WARN"))
    for w in warns:
        log("    WARN: " + w)

    return {
        "passed": bool(svm_ok and ur_ok),
        "von_mises_ok": bool(svm_ok),
        "radial_disp_ok": bool(ur_ok),
        "expected_svm_band_MPa": [svm_lo, svm_hi],
        "expected_ur_band_mm": [ur_lo, ur_hi],
        "band_definition": ("von Mises in [%.1f, %.1f] x analytic bore hoop; "
                            "delta_r in [%.0f, %.0f] um scaled by (n/18000)^2"
                            % (SVM_BAND_X_HOOP[0], SVM_BAND_X_HOOP[1],
                               UR_BAND_UM_18K[0], UR_BAND_UM_18K[1])),
        "measured_max_von_mises_MPa": _py(max_svm_MPa),
        "measured_max_radial_disp_mm": _py(max_ur_mm),
        "warnings": warns,
    }


