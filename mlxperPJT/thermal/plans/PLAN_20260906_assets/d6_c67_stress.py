def read_rst_dpf(rst, log):
    """ansys.dpf.core.  이 레포에 사용례가 없으므로 전 구간 방어적으로 감싼다."""
    from ansys.dpf import core as dpf                       # noqa: F401

    log("  DPF: opening model")
    model = dpf.Model(rst)
    mesh = model.metadata.meshed_region
    n_sets = 1
    try:
        n_sets = int(model.metadata.time_freq_support.n_sets)
    except Exception as exc:
        log("  DPF: n_sets unavailable (%s) -> assuming 1" % exc)

    node_ids = _np.asarray(mesh.nodes.scoping.ids, dtype=_np.int64)
    coords = _np.asarray(mesh.nodes.coordinates_field.data, dtype=float)
    coords = coords.reshape(node_ids.size, 3)

    # --- von Mises (nodal, averaged) -------------------------------------
    sop = model.results.stress()
    sop.inputs.time_scoping.connect([1])
    sop.inputs.requested_location.connect(dpf.locations.nodal)
    vm = dpf.operators.invariant.von_mises_eqv_fc(
        fields_container=sop.outputs.fields_container)
    f = vm.outputs.fields_container()[0]
    svm_raw = _align_to(node_ids, _np.asarray(f.scoping.ids), _np.asarray(f.data),
                        1, log=log, label="von Mises")

    # --- displacement -----------------------------------------------------
    dop = model.results.displacement()
    dop.inputs.time_scoping.connect([1])
    df = dop.outputs.fields_container()[0]
    u_raw = _align_to(node_ids, _np.asarray(df.scoping.ids),
                      _np.asarray(df.data).reshape(-1, 3), 3,
                      log=log, label="displacement")

    grid = None
    try:
        grid = mesh.grid
    except Exception as exc:
        log("  DPF: mesh.grid unavailable (%s) -> point cloud fallback" % exc)

    return {"nnum": node_ids, "xyz_raw": coords, "svm_raw": svm_raw,
            "u_raw": u_raw, "grid": grid, "n_sets": n_sets,
            "reader": "ansys.dpf.core",
            "averaging": "nodal (elemental-nodal averaged, DPF default)"}


def read_rst_mapdl_reader(rst, log):
    """ansys.mapdl.reader.read_binary -- 이 레포가 이미 쓰는 경로.

    thermal_viz.py:60 이 `from ansys.mapdl import reader as rd` 로 import 한다.
        nnum, pstr = res.principal_nodal_stress(0)
        von Mises  = pstr[:, 4]     (S1,S2,S3,SINT,SEQV 순서의 5번째)
        res.nodal_solution(0) -> (nnum, U)  변위
    principal_nodal_stress 는 결과가 없는 절점에 NaN 을 넣는다 -> nan-aware 통계 필수.
    """
    from ansys.mapdl import reader as rd

    log("  mapdl.reader: read_binary(%s)" % rst)
    res = rd.read_binary(rst)

    n_sets = 1
    try:
        n_sets = int(res.nsets)
    except Exception:
        try:
            n_sets = len(res.time_values)
        except Exception:
            pass
    log("  mapdl.reader: nsets = %d (using set 0)" % n_sets)

    mesh_nnum = _np.asarray(res.mesh.nnum, dtype=_np.int64)
    coords = _np.asarray(res.mesh.nodes, dtype=float)[:, :3]

    snum, pstr = res.principal_nodal_stress(0)
    pstr = _np.asarray(pstr, dtype=float)
    if pstr.ndim != 2 or pstr.shape[1] < 5:
        raise RuntimeError("principal_nodal_stress returned shape %r; expected "
                           "(n, >=5) = (S1, S2, S3, SINT, SEQV)" % (pstr.shape,))
    svm_raw = _align_to(mesh_nnum, _np.asarray(snum), pstr[:, 4], 1,
                        log=log, label="SEQV")

    dnum, U = res.nodal_solution(0)
    U = _np.asarray(U, dtype=float)
    if U.ndim != 2 or U.shape[1] < 2:
        raise RuntimeError("nodal_solution returned shape %r; expected (n, >=2) "
                           "ux/uy[/uz] -- is this a structural result file?"
                           % (U.shape,))
    # 2 DOF/node = 2D plane model (Motor-CAD mechanical is 2D).  The rotation axis is Z,
    # so u_r = ux*cos(th) + uy*sin(th) is unchanged; there simply is no uz.  Pad it with
    # zeros so everything downstream keeps working on an (n, 3) array.
    if U.shape[1] == 2:
        model_dim = "2D"
        log("  mapdl.reader: 2 DOF/node -> 2D plane model; uz padded with zeros "
            "(u_r = ux*cos(th) + uy*sin(th) is unaffected)")
        U = _np.column_stack([U[:, 0], U[:, 1], _np.zeros(len(U), dtype=float)])
    else:
        model_dim = "3D"
    u_raw = _align_to(mesh_nnum, _np.asarray(dnum), U[:, :3], 3,
                      log=log, label="displacement")

    grid = None
    try:
        grid = res.grid
    except Exception as exc:
        log("  mapdl.reader: res.grid unavailable (%s) -> point cloud fallback" % exc)

    return {"nnum": mesh_nnum, "xyz_raw": coords, "svm_raw": svm_raw,
            "u_raw": u_raw, "grid": grid, "n_sets": n_sets,
            "model_dim": model_dim,
            "reader": "ansys.mapdl.reader.read_binary",
            "averaging": "nodal (principal_nodal_stress column 4 = SEQV)"}


def _mapdl_load_db(mapdl, mech_dir, log):
    """MECH 폴더에서 DB 를 올린다.  .db -> .cdb -> ds.dat 순.

    Workbench MECH 폴더에는 보통 file.db 가 **없다**.  ds.dat 는 `/EXIT` 로 끝나므로
    그대로 input 하면 MAPDL 이 죽는다 -> 꼬리를 잘라 낸 사본을 만들어 넣는다.
    """
    from ansys.mapdl.core.errors import MapdlRuntimeError

    cands_db = [os.path.join(mech_dir, n) for n in ("file.db", "ds.db")]
    cands_cdb = [os.path.join(mech_dir, n) for n in ("file.cdb", "ds.cdb")]
    ds_dat = os.path.join(mech_dir, "ds.dat")

    for p in cands_db:
        if os.path.isfile(p):
            log("  MAPDL: resume(%s)" % p)
            try:
                mapdl.resume(p)
                return {"kind": "db", "path": p}
            except MapdlRuntimeError as exc:
                log("  MAPDL: resume failed (%s)" % str(exc)[:200])
    for p in cands_cdb:
        if os.path.isfile(p):
            stem = os.path.splitext(p)[0]
            log("  MAPDL: cdread('DB', %s, 'cdb')" % stem)
            try:
                mapdl.prep7()
                mapdl.cdread("DB", stem, "cdb")
                mapdl.finish()
                return {"kind": "cdb", "path": p}
            except MapdlRuntimeError as exc:
                log("  MAPDL: cdread failed (%s)" % str(exc)[:200])
    if os.path.isfile(ds_dat):
        trimmed = os.path.join(mapdl.directory, "ds_trimmed.dat")
        n_in, n_out = 0, 0
        with open(ds_dat, "r", encoding="utf-8", errors="replace") as fin:
            lines = fin.readlines()
        n_in = len(lines)
        keep = []
        for ln in lines:
            s = ln.strip().upper()
            if s.startswith("/EXIT") or s.startswith("/EOF"):
                break
            keep.append(ln)
        n_out = len(keep)
        with open(trimmed, "w", encoding="utf-8") as fo:
            fo.writelines(keep)
        log("  MAPDL: input(ds.dat) with the /EXIT tail trimmed (%d -> %d lines)"
            % (n_in, n_out))
        try:
            mapdl.input(trimmed)
            return {"kind": "ds.dat", "path": ds_dat,
                    "note": "tail trimmed at /EXIT; %d of %d lines used"
                            % (n_out, n_in)}
        except MapdlRuntimeError as exc:
            log("  MAPDL: input(ds.dat) failed (%s)" % str(exc)[:200])

    raise RuntimeError(
        "no MAPDL-loadable database in %s.  MAPDL /POST1 cannot read a lone .rst -- "
        "it needs file.db, a .cdb, or ds.dat.  Copy the WHOLE MECH folder, or use "
        "the reader route (--rst) instead." % mech_dir)


def _mapdl_extract(mapdl, log):
    """현재 /POST1 set 에서 SEQV 와 반경변위를 뽑는다."""
    seqv = _np.asarray(mapdl.post_processing.nodal_eqv_stress(), dtype=float)
    nnum = _np.asarray(mapdl.mesh.nnum, dtype=_np.int64)
    coords = _np.asarray(mapdl.mesh.nodes, dtype=float)[:, :3]
    # RSYS,1 = 전역 원통좌표 (축 = Z) -> UX 가 곧 u_r, UY 가 u_theta.
    mapdl.rsys(1)
    ur = _np.asarray(mapdl.post_processing.nodal_displacement("X"), dtype=float)
    ut = _np.asarray(mapdl.post_processing.nodal_displacement("Y"), dtype=float)
    uz = _np.asarray(mapdl.post_processing.nodal_displacement("Z"), dtype=float)
    mapdl.rsys(0)
    ux = _np.asarray(mapdl.post_processing.nodal_displacement("X"), dtype=float)
    uy = _np.asarray(mapdl.post_processing.nodal_displacement("Y"), dtype=float)
    U = _np.column_stack([ux, uy, uz])
    log("  MAPDL: extracted %d nodes (SEQV + RSYS,1 u_r)" % nnum.size)
    return {"nnum": nnum, "xyz_raw": coords, "svm_raw": seqv, "u_raw": U,
            "u_r_native": ur, "u_t_native": ut, "grid": None}


def solve_rst_mapdl(mech_dir, rpm_list, log, nproc=4, memory=None, run_dir=None):
    """MECH 폴더의 DB 를 올려 각 rpm 에서 원심하중 static 을 재솔브한다.

    원심하중은 `OMEGA, , , wz` (rad/s).  회전기준계용 `CGOMGA` 도, 컴포넌트용
    `CMOMEGA` 도 아니다.  회전중심은 원점(Discovery.json Rotation.Center=[0,0,0]).
    `mapdl.allsel("ALL")` 를 SOLVE 직전마다 반드시 부른다 -- SOLVE 는 현재 선택된
    요소만 푼다.  `mapdl.ignore_errors` 는 쓰지 않는다: MapdlRuntimeError 를 잡는다.
    """
    from ansys.mapdl.core import launch_mapdl
    from ansys.mapdl.core.errors import MapdlRuntimeError

    wd = run_dir or os.path.join(os.path.abspath(mech_dir), "_d6_mapdl_run")
    if not os.path.isdir(wd):
        os.makedirs(wd)
    log("  MAPDL: launching (run_location=%s, nproc=%d)" % (wd, nproc))
    kw = dict(run_location=wd, override=True, nproc=int(nproc),
              additional_switches="-smp")
    if memory:
        kw["memory"] = int(memory)
    mapdl = launch_mapdl(**kw)
    out = {}
    try:
        mapdl.clear()
        db = _mapdl_load_db(mapdl, mech_dir, log)
        log("  MAPDL: database loaded from %s (%s)" % (db["path"], db["kind"]))
        for rpm in rpm_list:
            w = omega_rad_s(rpm)
            log("  MAPDL: solving %.0f rpm  (OMEGA,,,%.10f rad/s)" % (rpm, w))
            try:
                mapdl.finish()
                mapdl.slashsolu()
                mapdl.antype("STATIC")
                mapdl.omega("", "", w)
                mapdl.allsel("ALL")          # SOLVE 는 선택된 것만 푼다 -- 필수
                mapdl.solve()
                mapdl.finish()
                mapdl.post1()
                mapdl.set(1, 1)
                out[float(rpm)] = _mapdl_extract(mapdl, log)
                out[float(rpm)]["omega_rad_s"] = w
                out[float(rpm)]["db"] = db
            except MapdlRuntimeError as exc:
                raise RuntimeError("MAPDL solve failed at %.0f rpm: %s"
                                   % (rpm, str(exc)[:400]))
    finally:
        try:
            mapdl.exit()
        except Exception:
            pass
    return out


