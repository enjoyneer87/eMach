def infer_stress_scale(raw_max_abs, log):
    """rst 는 solve 단위계로 저장된다.  Pa 이면 1e-6, MPa 이면 1.0 을 돌려준다."""
    if _is_nan(raw_max_abs) or raw_max_abs <= 0.0:
        log("  stress unit: undetermined (max|S| = %r) -> assuming MPa" % raw_max_abs)
        return 1.0, "undetermined->MPa"
    if raw_max_abs > STRESS_PA_THRESHOLD:
        log("  stress unit: max|S| = %.4g > %.0e -> native Pa, scaling by 1e-6"
            % (raw_max_abs, STRESS_PA_THRESHOLD))
        return 1.0e-6, "Pa"
    log("  stress unit: max|S| = %.4g <= %.0e -> native MPa, no scaling"
        % (raw_max_abs, STRESS_PA_THRESHOLD))
    return 1.0, "MPa"


def infer_length_scale(raw_max_abs, log):
    """좌표계 단위.  로터 OD 는 0.075 m 또는 75 mm 여야 한다."""
    if _is_nan(raw_max_abs) or raw_max_abs <= 0.0:
        log("  length unit: undetermined -> assuming mm")
        return 1.0, "undetermined->mm"
    if raw_max_abs < LENGTH_M_THRESHOLD:
        log("  length unit: max|xyz| = %.4g < %.1f -> native m, scaling by 1e3"
            % (raw_max_abs, LENGTH_M_THRESHOLD))
        return 1.0e3, "m"
    log("  length unit: max|xyz| = %.4g >= %.1f -> native mm, no scaling"
        % (raw_max_abs, LENGTH_M_THRESHOLD))
    return 1.0, "mm"


def derive_fields(fields, log):
    """xyz_mm 과 u_mm 에서 r, theta, u_r, |u| 를 만든다.

    u_r = ux*cos(th) + uy*sin(th),  th = atan2(y, x)   (회전축 = Z)
    `mlxperPJT/nvh/e10_paper_figs.py:58-60` (radial_amp) 와 동일한 정의.
    """
    xyz = fields["xyz_mm"]
    u = fields.get("u_mm")
    if _np is not None and isinstance(xyz, _np.ndarray):
        x, y = xyz[:, 0], xyz[:, 1]
        th = _np.arctan2(y, x)
        fields["r_mm"] = _np.hypot(x, y)
        fields["theta_deg"] = _np.degrees(th)
        if u is not None:
            fields["u_r_mm"] = u[:, 0] * _np.cos(th) + u[:, 1] * _np.sin(th)
            fields["u_mag_mm"] = _np.sqrt((u[:, :3] ** 2).sum(axis=1))
    else:
        n = len(xyz)
        r = [0.0] * n
        td = [0.0] * n
        ur = [0.0] * n if u is not None else None
        um = [0.0] * n if u is not None else None
        for i in range(n):
            xi, yi = float(xyz[i][0]), float(xyz[i][1])
            th = math.atan2(yi, xi)
            r[i] = math.hypot(xi, yi)
            td[i] = math.degrees(th)
            if u is not None:
                ux, uy, uz = float(u[i][0]), float(u[i][1]), float(u[i][2])
                ur[i] = ux * math.cos(th) + uy * math.sin(th)
                um[i] = math.sqrt(ux * ux + uy * uy + uz * uz)
        fields["r_mm"] = r
        fields["theta_deg"] = td
        if u is not None:
            fields["u_r_mm"] = ur
            fields["u_mag_mm"] = um
    log("  derived r/theta/u_r for %d nodes (u_r = ux*cos(th)+uy*sin(th), axis=%s)"
        % (len(fields["xyz_mm"]), ROTATION_AXIS))
    return fields


def _align_to(target_ids, src_ids, src_vals, ncol, log=None, label=""):
    """src_vals 를 target_ids 순서로 재배열한다 (numpy 필요).  없는 절점은 NaN.

    **절점 순서를 절대 가정하지 않는다.**  DPF 의 `field.scoping.ids` 는 메시의
    `nodes.scoping.ids` 와 다를 수 있고, reader 의 `principal_nodal_stress` 도
    결과가 있는 절점만 돌려준다.  적중률을 로그에 남겨서 "조용히 절반이 NaN"
    같은 사고를 눈에 보이게 한다.
    """
    if _np is None:
        raise RuntimeError("_align_to needs numpy")
    t = _np.asarray(target_ids, dtype=_np.int64)
    s = _np.asarray(src_ids, dtype=_np.int64)
    v = _np.asarray(src_vals, dtype=float)
    if v.ndim == 1:
        v = v.reshape(-1, 1)
    if v.shape[1] < ncol:
        raise RuntimeError("%s: expected >=%d component(s), got %d"
                           % (label or "field", ncol, v.shape[1]))
    v = v[:, :ncol]
    if s.size == t.size and bool(_np.array_equal(s, t)):
        out = v
        hit = int(t.size)
    else:
        lut = {}
        for i in range(s.size):
            lut[int(s[i])] = i
        out = _np.full((t.size, ncol), _np.nan, dtype=float)
        hit = 0
        for i in range(t.size):
            j = lut.get(int(t[i]))
            if j is not None:
                out[i, :] = v[j, :]
                hit += 1
    if log is not None:
        log("  align %-14s: %d/%d target nodes matched (%.1f %%)"
            % (label or "field", hit, t.size,
               100.0 * hit / max(int(t.size), 1)))
        if hit == 0:
            log("  WARN: zero overlap between the field scoping and the mesh node "
                "ids -- the result will be all-NaN")
    return out if ncol > 1 else out[:, 0]


