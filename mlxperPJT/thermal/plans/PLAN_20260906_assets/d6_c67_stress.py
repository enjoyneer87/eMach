def build_sweep(rated, args, sweep_rpm, method, ana_fn, log, resolved=None):
    """4 점 스윕.  method='scale' 이면 omega^2 스케일, 'resolve' 면 실제 솔브 결과."""
    pts = []
    for rpm in sweep_rpm:
        sc = omega2_scale(rpm, args.rpm)
        ana = ana_fn(rpm)
        p = {
            "rpm": float(rpm),
            "omega_rad_s": omega_rad_s(rpm),
            "scale_n2": sc,
            "hoop_analytic_inner_MPa": ana["sigma_theta_inner_MPa"],
            "hoop_analytic_outer_MPa": ana["sigma_theta_outer_MPa"],
            "ur_analytic_outer_mm": ana["u_r_outer_mm"],
        }
        if method == "resolve" and resolved and float(rpm) in resolved:
            r = resolved[float(rpm)]
            p["max_von_mises_MPa"] = r["max_von_mises_MPa"]
            p["max_radial_disp_mm"] = r["max_radial_disp_mm"]
            p["max_von_mises_node"] = r["max_von_mises_node"]
            p["max_radial_disp_node"] = r["max_radial_disp_node"]
            p["source"] = "direct MAPDL solve"
        else:
            p["max_von_mises_MPa"] = rated["max_von_mises_MPa"] * sc
            p["max_radial_disp_mm"] = rated["max_radial_disp_mm"] * sc
            p["max_von_mises_node"] = rated["max_von_mises_node"]
            p["max_radial_disp_node"] = rated["max_radial_disp_node"]
            p["source"] = ("omega^2 scaling from %.0f rpm" % args.rpm)
        p["yield_MPa"] = args.yield_MPa
        p["safety_factor"] = (None if args.yield_MPa is None
                              else float(args.yield_MPa) / p["max_von_mises_MPa"])
        pts.append(p)
        log("    %6.0f rpm  w=%10.4f rad/s  (n/n_ref)^2=%.6f  svm=%10.4f MPa  "
            "d_r=%.6f mm  [%s]"
            % (p["rpm"], p["omega_rad_s"], p["scale_n2"],
               p["max_von_mises_MPa"], p["max_radial_disp_mm"], p["source"]))

    out = {
        "_method": ("resolve" if method == "resolve"
                    else "analytic_omega2_scaling_from_%.0frpm" % args.rpm),
        "_method_requested": method,
        "_method_options": ["resolve", "analytic_omega2_scaling_from_<ref>rpm"],
        "_reference_rpm": float(args.rpm),
        "_scaling_identity": ("sigma(n) = sigma(n_ref)*(n/n_ref)^2 and "
                              "delta_r(n) = delta_r(n_ref)*(n/n_ref)^2 -- EXACT, not "
                              "an approximation, for a linear elastic body under a "
                              "pure centrifugal body load with homogeneous "
                              "displacement BCs."),
        "_scaling_valid_if": ("linear elastic material; bonded (not frictional) "
                              "contact; no interference fit / sleeve / banding / "
                              "thermal preload; NLGEOM and spin softening off"),
        "_scaling_invalid_for": ("frictional contact (open/close state changes with "
                                 "speed), any plasticity, and ANY Neuber/Glinka "
                                 "plastic-corrected value -- scale the ELASTIC value "
                                 "first, then re-apply the correction at each speed"),
        "_c67_status": ("C67 has Sleeve_Thickness = Banding_Thickness = "
                        "Shaft_Hole_Diameter = 0 mm (Max3D L118-L120), so there is no "
                        "speed-independent constant term.  Whether the magnet-to-lam "
                        "interface is bonded or frictional (AdhesionFactor_Magnets = "
                        "0.2) decides whether the scaling is exact."),
        "points": pts,
    }
    return out


