def _is_nan(v):
    try:
        return v != v
    except Exception:
        return True


def _nanargmax(a):
    """NaN 을 건너뛰는 argmax.  전부 NaN 이면 -1."""
    if _np is not None and isinstance(a, _np.ndarray):
        if not _np.any(_np.isfinite(a)):
            return -1
        return int(_np.nanargmax(a))
    best_i, best_v = -1, None
    for i, v in enumerate(a):
        if _is_nan(v):
            continue
        if best_v is None or v > best_v:
            best_i, best_v = i, v
    return best_i


def _nanmax(a):
    i = _nanargmax(a)
    return float("nan") if i < 0 else float(a[i])


def _nanmin(a):
    if _np is not None and isinstance(a, _np.ndarray):
        if not _np.any(_np.isfinite(a)):
            return float("nan")
        return float(_np.nanmin(a))
    best = None
    for v in a:
        if _is_nan(v):
            continue
        if best is None or v < best:
            best = v
    return float("nan") if best is None else float(best)


def _nanmean(a):
    if _np is not None and isinstance(a, _np.ndarray):
        if not _np.any(_np.isfinite(a)):
            return float("nan")
        return float(_np.nanmean(a))
    s, n = 0.0, 0
    for v in a:
        if _is_nan(v):
            continue
        s += float(v)
        n += 1
    return float("nan") if n == 0 else s / n


def _nanmaxabs(a):
    if _np is not None and isinstance(a, _np.ndarray):
        b = _np.abs(_np.asarray(a, dtype=float))
        if not _np.any(_np.isfinite(b)):
            return float("nan")
        return float(_np.nanmax(b))
    best = None
    for v in a:
        if _is_nan(v):
            continue
        v = abs(float(v))
        if best is None or v > best:
            best = v
    return float("nan") if best is None else best


def _percentile(a, q):
    """numpy 없으면 정렬 기반 근사.  컨투어 clim 용이라 정밀도 요구가 낮다."""
    if _np is not None and isinstance(a, _np.ndarray):
        b = a[_np.isfinite(a)]
        if b.size == 0:
            return float("nan")
        return float(_np.percentile(b, q))
    vals = sorted(float(v) for v in a if not _is_nan(v))
    if not vals:
        return float("nan")
    k = (len(vals) - 1) * q / 100.0
    lo, hi = int(math.floor(k)), int(math.ceil(k))
    if lo == hi:
        return vals[lo]
    return vals[lo] * (hi - k) + vals[hi] * (k - lo)


def _py(obj):
    """numpy 스칼라/배열을 json 이 먹을 수 있는 순수 파이썬으로 변환."""
    if obj is None or isinstance(obj, (bool, str)):
        return obj
    if isinstance(obj, dict):
        return dict((str(k), _py(v)) for k, v in obj.items())
    if isinstance(obj, (list, tuple)):
        return [_py(v) for v in obj]
    if isinstance(obj, float):
        return None if (obj != obj or obj in (float("inf"), float("-inf"))) else obj
    if isinstance(obj, int):
        return obj
    if _np is not None and isinstance(obj, _np.generic):
        return _py(obj.item())
    if _np is not None and isinstance(obj, _np.ndarray):
        return _py(obj.tolist())
    return obj


