def synthetic_fields(args, log, kt=None):
    """해석해 회전 원환에서 합성 절점장을 만든다.

    닫힌해의 sigma_r / sigma_theta 로 평면응력 von Mises 를 만들고, 보어 근처
    한 줄에 브리지 응력집중 계수 kt 를 곱해 FE 다운 최대값을 만든다.
    합성이라도 **파이프라인(단위 판별 -> 파생 -> 최대값 -> 게이트 -> 스윕 -> JSON ->
    그림)은 실제 경로와 완전히 동일한 코드**를 지난다.
    """
    kt = float(args.dry_run_kt if kt is None else kt)
    a = args.shaft_r_mm / 1000.0
    b = args.rotor_r_mm / 1000.0
    ana = annulus_plane_stress(args.rpm, a, b, args.poisson, args.rho,
                               args.E_GPa * 1e9)
    fn = ana["_field_fn"]

    n_r, n_t, n_z = int(args.dry_run_nr), int(args.dry_run_nt), int(args.dry_run_nz)
    zs = [(-args.stack_mm / 2.0 + args.stack_mm * k / max(n_z - 1, 1))
          for k in range(n_z)]

    nnum, xyz, svm, u = [], [], [], []
    nid = 0
    for k in range(n_z):
        for i in range(n_r):
            r = a + (b - a) * i / float(n_r - 1)
            sr, st = fn["s_r"](r), fn["s_t"](r)
            vm = math.sqrt(st * st - st * sr + sr * sr) / 1e6      # MPa
            urad = fn["u_r"](r) * 1000.0                            # mm
            for j in range(n_t):
                th = 2.0 * math.pi * j / float(n_t)
                nid += 1
                # 브리지 모사: 8 극이므로 45 deg 간격의 좁은 섹터 x 보어 근처에서
                # 응력집중 kt 를 준다.  (합성이라는 사실은 JSON 에 명시된다.)
                pol = abs(math.cos(4.0 * th))
                conc = 1.0 + (kt - 1.0) * (pol ** 24) * (1.0 - (r - a) / (b - a)) ** 2
                nnum.append(nid)
                xyz.append([r * math.cos(th) * 1000.0,
                            r * math.sin(th) * 1000.0, zs[k]])
                svm.append(vm * conc)
                u.append([urad * math.cos(th), urad * math.sin(th), 0.0])

    if _np is not None:
        nnum = _np.asarray(nnum, dtype=_np.int64)
        xyz = _np.asarray(xyz, dtype=float)
        svm = _np.asarray(svm, dtype=float)
        u = _np.asarray(u, dtype=float)
    log("  synthetic field: %d nodes (n_r=%d, n_theta=%d, n_z=%d), Kt=%.2f"
        % (len(nnum), n_r, n_t, n_z, kt))
    return {"nnum": nnum, "xyz_raw": xyz, "svm_raw": svm, "u_raw": u,
            "grid": None, "n_sets": 1,
            "reader": "synthetic (dry-run, analytic rotating annulus x Kt)",
            "averaging": "n/a (synthetic)",
            "_kt": kt}


